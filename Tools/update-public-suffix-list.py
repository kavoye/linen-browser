#!/usr/bin/env python3
"""Refresh Linen/Resources/PublicSuffixList.txt from publicsuffix.org.

Writes one rule per line in ASCII (internationalised names become punycode),
without comments, so the app matches rules against URL.host() directly.
"""

from pathlib import Path
from urllib.request import urlopen


SOURCE = "https://publicsuffix.org/list/public_suffix_list.dat"
OUTPUT = Path(__file__).resolve().parent.parent / "Linen/Resources/PublicSuffixList.txt"


def ascii_rule(rule: str) -> str:
    prefix = ""
    if rule.startswith("!"):
        prefix, rule = "!", rule[1:]
    labels = [
        label if label == "*" or label.isascii() else label.encode("idna").decode("ascii")
        for label in rule.split(".")
    ]
    return prefix + ".".join(labels).lower()


def main() -> None:
    with urlopen(SOURCE, timeout=30) as response:
        text = response.read().decode("utf-8")
    if "===BEGIN PRIVATE DOMAINS===" not in text:
        raise SystemExit("The download is not the public suffix list.")
    rules = []
    for line in text.splitlines():
        rule = line.strip().split(" ")[0]
        if rule and not rule.startswith("//"):
            rules.append(ascii_rule(rule))
    header = f"// Public Suffix List, {SOURCE}\n// Mozilla Public License 2.0. Generated by Tools/update-public-suffix-list.py.\n"
    OUTPUT.write_text(header + "\n".join(sorted(set(rules))) + "\n", encoding="utf-8")
    print(f"Wrote {len(set(rules))} rules to {OUTPUT}")


if __name__ == "__main__":
    main()
